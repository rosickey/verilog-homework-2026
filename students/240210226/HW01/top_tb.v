`timescale 1ns / 1ns
//----------------------------------------------------------------------
// top_tb.v  --  CD4017 十进制计数器仿真测试平台
//
// 结构:
//   u_clk_gen : clk_gen 模块,产生方波作为计数时钟
//   u_cd4017  : 被测的 CD4017 十进制计数器
//
// 激励安排:
//   时段            clr   en    观察内容
//   ------------------------------------------------
//   0 ~ 35ns         1     0    清零,输出停留在 Q0
//   35ns ~ 345ns     0     1    正常计数,Q0 依次移向 Q9 并循环
//   345ns ~ 405ns    0     0    撤销使能,计数暂停,输出保持
//   405ns ~ 445ns    0     1    恢复使能,继续计数
//   445ns ~ 475ns    1     x    计数途中清零,输出立即回到 Q0
//   475ns ~ 700ns    0     1    清零释放后重新计数
//   700ns                     仿真结束
//----------------------------------------------------------------------

module top_tb;

    //---------------- 信号定义 ----------------
    wire        clk;                // clk_gen 产生的方波
    reg         en;                 // 使能
    reg         clr;                // 清零
    wire [9:0]  q;                  // CD4017 的十进制输出

    //---------------- 例化时钟激励模块 ----------------
    // 直接使用课堂订正的 clk_gen.v,不覆盖参数,保证接口兼容
    clk_gen u_clk_gen
    (
        .clk (clk)
    );

    //---------------- 例化被测模块 ----------------
    cd4017 u_cd4017
    (
        .clk (clk),
        .en  (en),
        .clr (clr),
        .q   (q)
    );

    //---------------- 当前有效的输出编号(便于观察) ----------------
    reg [3:0] idx;                  // 哪一位为 1,即当前处于 Qn
    integer   i;

    always @(*) begin
        idx = 4'hF;                 // 无有效输出时记为 F
        for (i = 0; i < 10; i = i + 1) begin
            if (q[i]) idx = i;
        end
    end

    //---------------- 激励产生 ----------------
    initial begin
        // 波形文件,供 GTKWave 查看并截图
        $dumpfile("wave.vcd");
        $dumpvars(0, top_tb);

        // 打印便于核对的状态
        $display(" time | clk en clr |    q       | active");
        $monitor("%5t |  %b   %b   %b  | %b | Q%0d",
                 $time, clk, en, clr, q, idx);

        en  = 1'b0;
        clr = 1'b1;                 // 先清零

        #35  clr = 1'b0;            // 35ns 释放清零
        #10  en  = 1'b1;            // 45ns 使能,开始计数

        #300 en  = 1'b0;            // 345ns 撤销使能,计数暂停
        #60  en  = 1'b1;            // 405ns 恢复使能

        #40  clr = 1'b1;            // 445ns 计数途中清零
        #30  clr = 1'b0;            // 475ns 释放清零,重新计数

        #225 $display("simulation finished at %0t ns", $time);
        $finish;
    end

endmodule
