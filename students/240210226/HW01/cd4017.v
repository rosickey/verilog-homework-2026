`timescale 1ns / 1ns
//----------------------------------------------------------------------
// cd4017.v  --  十进制计数器 / 脉冲分配器 CD4017
//
// 端口:
//   clk : 计数时钟,上升沿有效
//   en  : 使能端,en=1 时允许计数;en=0 时计数暂停,输出保持
//   clr : 清零端,高电平有效;清零时输出回到 Q0(即 q[0]=1,其余为 0)
//   q   : 十进制输出 q[9:0],任何时刻只有一个为 1,依次循环
//
// 工作原理:
//   采用环形移位的方式实现十进制计数:初值为 10'b00_0000_0001,
//   每个有效时钟上升沿把唯一的那个 "1" 向高位移动一位,移出 q[9]
//   后回到 q[0],形成 Q0→Q1→…→Q9→Q0 的十拍循环,共 10 个状态。
//----------------------------------------------------------------------

module cd4017
(
    input               clk,
    input               en,
    input               clr,
    output reg  [9:0]   q
);

    // 异步清零:clr 一拉高立即回到 Q0,不必等待时钟沿
    always @(posedge clk or posedge clr) begin
        if (clr) begin
            q <= 10'b00_0000_0001;      // 清零,输出 Q0
        end
        else if (en) begin
            q <= {q[8:0], q[9]};        // 有效沿且使能时循环左移一位
        end
    end

endmodule
