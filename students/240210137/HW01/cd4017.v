`timescale 1ns/1ns
//----------------------------------------------------------------------
// cd4017.v  --  十进制计数器 / 脉冲分配器 CD4017
//
// 端口：
//   clk : 计数时钟，上升沿有效
//   en  : 计数使能端，高电平时允许计数，低电平时输出保持不变
//   clr : 异步清零端，高电平有效，清零后输出回到 Q0（q[0] = 1）
//   q   : 十进制输出 q[9:0]，任一时刻只有一位为 1，
//         按照 Q0→Q1→…→Q9→Q0 的顺序循环，共 10 个状态
//
// 实现思路：
//   用一个 "1" 在 q[9:0] 中循环左移来实现十进制计数，被移出 q[9] 的位
//   从 q[0] 移入，所以每来 10 个有效时钟上升沿，输出循环一次。
//----------------------------------------------------------------------

module CD4017(clk, en, clr, q);

input        clk;
input        en;
input        clr;
output [9:0] q;

reg [9:0] q;

always @(posedge clk or posedge clr)
begin
    if (clr)
        q <= 10'b0000000001;            // 异步清零，输出 Q0
    else if (en)
        q <= {q[8:0], q[9]};            // 使能时循环左移一位
end

endmodule
