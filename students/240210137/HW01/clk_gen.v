`timescale 1ns/1ns
//----------------------------------------------------------------------
// clk_gen.v  --  方波激励（时钟）产生模块
//
// 课堂订正的模块，用于测试平台中产生计数时钟：
// q 的每一次计数需要 clk 的一个上升沿，#10 表示半个周期为 10ns，
// 因此输出方波周期为 20ns，高低电平各占一半。
//----------------------------------------------------------------------

module clk_gen(clk);

output reg clk;

initial
begin
    clk = 0;
    forever #10 clk = ~clk;
end

endmodule
