`timescale 1ns/1ns

//============================================================
// 模块名称：top_tb
// 功能描述：顶层测试平台，CD4017 十进制计数器仿真
//           实例化 clk_gen 提供方波激励
//           实例化 cd4017 作为被测模块
//============================================================
module top_tb;

    //---------- 内部信号线定义 ----------
    wire       clk;    // 时钟信号，由 clk_gen 驱动
    reg        clr;    // 清零信号，在 initial 中赋值
    reg        en;     // 使能信号，在 initial 中赋值
    wire [9:0] q;      // cd4017 的 10 位独热码输出

    //---------- 模块实例化 ----------

    // 1. 时钟生成模块：产生周期 20ns 的方波
    clk_gen u_clk(
        .clk(clk)
    );

    // 2. CD4017 十进制计数器（被测模块）
    cd4017 u_cd4017(
        .clk(clk),
        .en(en),
        .clr(clr),
        .q(q)
    );

    //---------- 波形记录 ----------
    initial begin
        $dumpfile("top_tb.vcd");
        $dumpvars(0, top_tb);
    end

    //---------- 测试激励 ----------
    initial begin
        // 初始状态：清零有效，使能无效
        clr = 1'b1;
        en  = 1'b0;

        #20 clr = 1'b0;     // 20ns 后释放清零，q[0]=1
        #10 en  = 1'b1;     // 再 10ns（共 30ns）后使能有效，开始计数

        #300 $finish;       // 仿真运行到 330ns 结束
    end

endmodule
